const int MAX_ALLOWED_MSG_SIZE = 65536;
static char* SERV_IP;
static uint16_t SERV_PORT;

struct Conn {
    int fd = -1;
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;
    bool is_replica = false;
    bool is_upstream = false;
    replication::State replication;
    // buffered input and output
    std::vector<uint8_t> incoming;  // data to be parsed by the application
    std::vector<uint8_t> outgoing;  // responses generated by the application
};

static int server_listen_fd = -1;
static std::vector<Conn*>* server_connections = nullptr;

void fd_set_nb(int fd){ // set fd as non blocking
    errno = 0;
    int flags = fcntl(fd, F_GETFL, 0);
    if (errno) {
        perror("fcntl error");
        abort();
    }

    flags |= O_NONBLOCK;

    errno = 0;
    (void)fcntl(fd, F_SETFL, flags);
    if (errno) {
        perror("fcntl error");
        abort();
    }
}

void append(std::vector<uint8_t> &v, const uint8_t* buff, size_t n){
    v.insert(v.end(), buff, buff + n);
}

void erase_from_start(std::vector<uint8_t> &v, size_t n){
    v.erase(v.begin(), v.begin() + n);
}

Conn* handle_new_connection(int sockfd){
    struct sockaddr_in clientaddr{};
    socklen_t clientlen = sizeof(clientaddr);
    int client_fd = accept(sockfd, (struct sockaddr* ) &clientaddr, &clientlen);
    if(client_fd<0){
        perror("accept in failed");
        return NULL;
    }

    char client_ip[INET_ADDRSTRLEN];
    if (inet_ntop(AF_INET, &clientaddr.sin_addr, client_ip, sizeof(client_ip))) {
        std::cout << "New client: " << client_ip << ": " << ntohs(clientaddr.sin_port) << " connected\n";
    }

    fd_set_nb(client_fd);
    Conn* conn = new Conn();
    conn->fd = client_fd;
    conn->want_read = true;
    return conn;
}

void make_response(Response &res, Conn *conn){
    uint32_t res_len = (uint32_t)(res.data.size() + 4);
    
    append(conn->outgoing, (const uint8_t*)&res_len, 4);
    append(conn->outgoing, (const uint8_t*)&res.status, 4);
    append(conn->outgoing, res.data.data(), (size_t)res.data.size());
    conn->want_write = true;
}

static bool start_replica_snapshot(Conn* conn) {
    std::vector<int> inherited_fds;
    if (server_connections != nullptr) {
        for (Conn* existing : *server_connections) {
            if (existing != nullptr) {
                inherited_fds.push_back(existing->fd);
                if (existing->replication.pipe_fd >= 0) {
                    inherited_fds.push_back(existing->replication.pipe_fd);
                }
            }
        }
    }
    return replication::start_snapshot(conn->replication, server_listen_fd,
                                        inherited_fds, aof_sequence());
}

bool try_processing_one(Conn* conn){
    if(conn->incoming.size() < 4){
        return false; // wait for some time
    }
    uint32_t msg_len = 0;
    memcpy(&msg_len, conn->incoming.data(), 4);

    if(msg_len>MAX_ALLOWED_MSG_SIZE){
        std::cout << "Message size is too big, dropping connection" << "\n";
        conn->want_close = true;
        return false;
    }

    if(conn->incoming.size() < 4 + msg_len){
        return false; // wait more
    }

    std::vector<uint8_t>req(msg_len);
    memcpy(req.data(), conn->incoming.data() + 4, msg_len);

    std::vector<std::string> cmd;

    if(deserialize(req.data(), (size_t)(req.size()), cmd) < 0){
        conn->want_close = true;
        return false;
    }

    if (!cmd.empty() && (cmd[0] == "sync_reset" || cmd[0] == "replicate") && !conn->is_upstream) {
        conn->want_close = true;
        return false;
    }

    uint64_t replicated_sequence = 0;
    Response res;
    RequestResult result = do_request(cmd, res, &replicated_sequence);

    if (result == RequestResult::RegisterReplica) {
        conn->is_replica = true;
        if (!start_replica_snapshot(conn)) {
            conn->want_close = true;
        }
        erase_from_start(conn->incoming, 4 + msg_len);
        return true;
    }

    if (result == RequestResult::ResetDatabase) {
        reset_aof();
        erase_from_start(conn->incoming, 4 + msg_len);
        return true;
    }

    if (result == RequestResult::ReplicatedWrite) {
        append_only_file_at_sequence(cmd, replicated_sequence);
        erase_from_start(conn->incoming, 4 + msg_len);
        return true;
    }

    if(result == RequestResult::Processed and is_write_command(cmd) and res.status == RES_OK){
        append_only_file(cmd);
        if (server_connections != nullptr) {
            for (Conn* replica : *server_connections) {
                if (replica != nullptr && replica->is_replica && !replica->want_close) {
                    replication::queue_command(replica->replication, cmd, aof_sequence(),
                                               replica->outgoing, replica->want_write,
                                               replica->want_close);
                }
            }
        }
    }

    if (conn->is_upstream) {
        erase_from_start(conn->incoming, 4 + msg_len);
        return true;
    }

    make_response(res,conn);

    erase_from_start(conn->incoming, 4+msg_len);

    return true;
}

void handle_write(Conn* conn){
    ssize_t n = write(conn->fd, conn->outgoing.data(), (size_t)(conn->outgoing.size()));

    if(n < 0 and (errno == EAGAIN || errno == EWOULDBLOCK)){
        return ;
    }
    if(n < 0){
        conn->want_close = true;
        return;
    }

    erase_from_start(conn->outgoing, n);

    if(conn->outgoing.size() == 0){
        conn->want_read = true;
        conn->want_write = false;
    }
    replication::pump_backlog(conn->replication, conn->outgoing, conn->want_write);
}


void handle_read(Conn* conn){
    uint8_t buff[65536];
    ssize_t n = read (conn->fd, buff, sizeof(buff));
    if(n<0 and errno == EAGAIN){
        return ; // nothing to read
    }
    if(n < 0){
        if(errno == EAGAIN || errno == EWOULDBLOCK){
            return;
        }
        if(errno == EINTR){
            return;
        }
        conn->want_close = true;
        return;
    }
    if(n == 0){
        conn->want_close = true;
        return;
    }

    append(conn->incoming, buff, n);

    while(try_processing_one(conn)){};

    if(conn->outgoing.size() > 0){
        conn->want_read = false;
        conn->want_write = true;
        handle_write(conn);
    }
}

static bool queue_sync_command(Conn* conn) {
    std::vector<std::string> cmd{"sync"};
    std::vector<uint8_t> payload;
    if (serialize(cmd, payload) < 0) {
        return false;
    }

    uint32_t msg_len = (uint32_t)(payload.size());
    append(conn->outgoing, (const uint8_t*)(&msg_len), sizeof(msg_len));
    append(conn->outgoing, payload.data(), payload.size());
    conn->want_write = true;
    return true;
}

int main(int argc, char **argv){

    if(argc!=3){
        std::cerr << "Usage: " << argv[0] << " <IP> <PORT>\n";
        exit(1);
    }

    SERV_IP = argv[1];
    SERV_PORT = (uint16_t)(std::stoi(argv[2]));

    char aof_path[128];
    std::snprintf(aof_path, sizeof(aof_path), "persistence/appendonly_%u.aof", SERV_PORT);
    set_aof_path(aof_path);

    int sockfd;
    if( (sockfd = socket(AF_INET, SOCK_STREAM, 0)) < 0){
        perror("socket creation failed");
        exit(1);
    }

    int val = 1;
    setsockopt(sockfd, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val));

    struct sockaddr_in servaddr{};
    servaddr.sin_family = AF_INET;
    servaddr.sin_port = htons(SERV_PORT);
    inet_pton(AF_INET, SERV_IP , &servaddr.sin_addr);

    if( (bind (sockfd, (struct sockaddr *) &servaddr, sizeof(servaddr))) <0){
        perror("socket bind failed");
        exit(1);
    }


    if( (listen(sockfd, SOMAXCONN)) < 0){
        perror("listen failed");
        exit(1);
    }

    std::vector<Conn *> fd2conn;
    std::vector<struct pollfd> poll_args;
    server_listen_fd = sockfd;
    server_connections = &fd2conn;

    load_aof(); // read and restore the db from appendonly.aof file

    if (!is_master(SERV_IP, SERV_PORT)) {
        char master_ip[64] = {};
        uint16_t master_port = 0;
        if (!get_master_address(master_ip, sizeof(master_ip), &master_port)) {
            std::cerr << "Could not read master address from sentinel\n";
            return 1;
        }

        int master_fd = socket(AF_INET, SOCK_STREAM, 0);
        if (master_fd < 0) {
            perror("master socket");
            return 1;
        }

        sockaddr_in master_addr{};
        master_addr.sin_family = AF_INET;
        master_addr.sin_port = htons(master_port);
        if (inet_pton(AF_INET, master_ip, &master_addr.sin_addr) != 1 ||
            connect(master_fd, reinterpret_cast<sockaddr*>(&master_addr), sizeof(master_addr)) < 0) {
            perror("connect to master");
            close(master_fd);
            return 1;
        }

        fd_set_nb(master_fd);
        Conn* replica_conn = new Conn();
        replica_conn->fd = master_fd;
        replica_conn->want_read = true;
        replica_conn->is_upstream = true;
        if (!queue_sync_command(replica_conn)) {
            std::cerr << "Could not encode sync command\n";
            close(master_fd);
            delete replica_conn;
            return 1;
        }
        if (fd2conn.size() <= static_cast<size_t>(master_fd)) {
            fd2conn.resize(static_cast<size_t>(master_fd) + 1);
        }
        fd2conn[master_fd] = replica_conn;
    }

    while(true){
        poll_args.clear();
        std::vector<Conn*> poll_connections;
        std::vector<bool> pipe_events;

        struct pollfd pfd = {sockfd, POLLIN, 0};
        poll_args.push_back(pfd);
        poll_connections.push_back(nullptr);
        pipe_events.push_back(false);
        for( Conn* conn : fd2conn){
            if(!conn)continue;
            struct pollfd pfd = {conn->fd, POLLERR, 0};
            if(conn->want_read){
                pfd.events |= POLLIN;
            }
            if(conn->want_write){
                pfd.events |= POLLOUT;
            }
            poll_args.push_back(pfd);
            poll_connections.push_back(conn);
            pipe_events.push_back(false);
            if (replication::should_poll_pipe(conn->replication, conn->outgoing.size())) {
                struct pollfd pipe_pfd = {replication::pipe_fd(conn->replication), POLLIN, 0};
                poll_args.push_back(pipe_pfd);
                poll_connections.push_back(conn);
                pipe_events.push_back(true);
            }
        }

        int ready = poll(poll_args.data(), static_cast<nfds_t>(poll_args.size()), -1);
        
        if(ready<0 and errno == EINTR ){
            continue;
        }
        if(ready<0){
            perror("poll");
            abort();
        }

        if(poll_args[0].revents){
            Conn* conn = handle_new_connection(poll_args[0].fd);
            if (conn == nullptr) {
                continue;
            }
            if(fd2conn.size() <= (size_t)conn->fd){
                fd2conn.resize(conn->fd+1);
            }
            fd2conn[conn->fd] = conn;
        }

        for(size_t i = 1; i < poll_args.size(); i++){
            struct pollfd pfd = poll_args[i];
            if(pfd.revents == 0){
                continue;
            }
            Conn* conn = poll_connections[i];
            if (conn == nullptr) {
                continue;
            }
            if (pipe_events[i]) {
                if (pfd.revents & (POLLIN | POLLHUP | POLLERR)) {
                    if (!replication::read_snapshot(conn->replication, conn->outgoing,
                                                    conn->want_write)) {
                        conn->want_close = true;
                    }
                }
                continue;
            }
            if(pfd.revents & POLLIN){
                assert(conn->want_read);
                handle_read(conn);
            }
            if(pfd.revents & POLLOUT){
                assert(conn->want_write);
                handle_write(conn);
            }
            if (pfd.revents & (POLLERR | POLLHUP | POLLNVAL)) {
                conn->want_close = true;
            }
        }

        for (Conn*& conn : fd2conn) {
            if (conn == nullptr || !conn->want_close) {
                continue;
            }
            replication::cleanup(conn->replication);
            close(conn->fd);
            delete conn;
            conn = nullptr;
        }
    }
    return 0;
}